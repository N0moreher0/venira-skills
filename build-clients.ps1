<#
.SYNOPSIS
  Rebuild the per-client drop-in files under clients/ from src/.
  Combined files carry begin/end markers so installers can refresh a marked
  block without touching anything else in the target file.

.EXAMPLE
  .\build-clients.ps1
#>
[CmdletBinding()]
param([string]$Root = $null)
if (-not $Root) { $Root = Split-Path -Parent $PSCommandPath }
if (-not $Root) { $Root = $PWD.Path }

$skills = Get-ChildItem -Directory -Path (Join-Path $Root 'src') | Sort-Object Name
if (-not $skills) { throw "no skills under $Root" }

$begin = '<!-- venira-skills:begin -->'
$end = '<!-- venira-skills:end -->'
$stamp = '<!-- generated by build-clients.ps1; do not edit by hand. edit src/<skill>/SKILL.md and rerun. -->'

function Join-Paths { Join-Path $args[0] (($args[1..($args.Length-1)]) -join '\') }

function Build-Combined($rel) {
  $file = if (Test-Path $rel) { $rel } else { Join-Path $Root $rel }
  $body = @()
  $body += $begin
  $body += $stamp
  $body += ''
  $body += '# Venira skills (auto-activated heuristics; call tools by name if unsure)'
  $body += ''
  foreach ($skill in $skills) {
    $src = Join-Path $skill.FullName 'SKILL.md'
    $body += "<!-- venira-skill:$($skill.Name) -->"
    $body += (Get-Content -Raw $src).TrimEnd()
    $body += ''
    $body += "<!-- /venira-skill:$($skill.Name) -->"
    $body += ''
  }
  $body += $end
  New-Item -ItemType Directory -Force (Split-Path $file) | Out-Null
  Set-Content -Path $file -Value ($body -join "`n") -Encoding utf8
  Write-Host "built $rel"
}

Build-Combined 'clients\opencode\AGENTS.md'
Build-Combined 'clients\codex\AGENTS.md'
Build-Combined 'clients\antigravity\GEMINI.md'

$skillsDest = Join-Path $Root 'clients\claude-code\skills'
if (Test-Path $skillsDest) { Remove-Item $skillsDest -Recurse -Force }
foreach ($skill in $skills) {
  $dest = Join-Path $skillsDest $skill.Name
  New-Item -ItemType Directory -Force $dest | Out-Null
  Copy-Item (Join-Path $skill.FullName 'SKILL.md') (Join-Path $dest 'SKILL.md')
}
Write-Host "built clients\claude-code\skills\ ($($skills.Count) skills)"
